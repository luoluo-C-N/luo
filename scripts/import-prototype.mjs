import fs from 'node:fs';
const source = process.env.PROTOTYPE_SOURCE || 'reference/admin-app.v2-crud.html';
let html=fs.readFileSync(source,'utf8');
const css=[];html=html.replace(/<style>([\s\S]*?)<\/style>/g,(_,s)=>{css.push(s);return ''});
const js=[];html=html.replace(/<script>([\s\S]*?)<\/script>/g,(_,s)=>{js.push(s);return ''});
html=html.replace('width=device-width, initial-scale=1.0','width=device-width, initial-scale=1.0, viewport-fit=cover');
html=html.replace(/<title>.*?<\/title>/,'<title>掌上小站 · 0.01</title>');
html=html.replace('</head>','<meta name="theme-color" content="#EAF0FA"><link rel="manifest" href="/manifest.webmanifest"><link rel="stylesheet" href="/src/prototype.css"><link rel="stylesheet" href="/src/mobile.css"><script src="/src/boot.js"></script></head>');
html=html.replace('</body>','<script src="/src/prototype.js"></script><script type="module" src="/src/app.js"></script></body>');
fs.writeFileSync('index.html',html);fs.writeFileSync('src/prototype.css',css.join('\n'));fs.writeFileSync('src/prototype.js',js.join('\n'));
console.log(`Snapshot split from ${source}`,css.length,js.length);
